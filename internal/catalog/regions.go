var regionByShort map[string]Region

func init() {
	regionByShort = make(map[string]Region, len(Regions))
	for _, r := range Regions {
		regionByShort[r.Short] = r
	}
}

// RegionByShort возвращает регион по короткому коду (77, 50, …).
func RegionByShort(short string) (Region, bool) {
	r, ok := regionByShort[strings.TrimSpace(short)]
	return r, ok
}

// SearchRegions ищет регионы по названию или коду.
func SearchRegions(query string, limit int) []Region {
	q := strings.TrimSpace(strings.ToLower(query))
	if q == "" || limit <= 0 {
		return nil
	}
	if r, ok := RegionByShort(q); ok {
		return []Region{r}
	}
	var out []Region
	for _, r := range Regions {
		name := strings.ToLower(r.Name)
		if strings.Contains(name, q) || r.Short == q || strings.HasPrefix(r.Code, q) {
			out = append(out, r)
		}
	}
	sort.Slice(out, func(i, j int) bool {
		return out[i].Name < out[j].Name
	})
	if len(out) > limit {
		out = out[:limit]
	}
	return out
}
